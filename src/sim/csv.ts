import type { TelemetrySample } from "./types";

const columns = [
  "timestamp",
  "torpedo_x",
  "torpedo_z",
  "target_x",
  "target_z",
  "estimate_x",
  "estimate_z",
  "range",
  "horizontal_range",
  "vertical_separation",
  "closing_velocity",
  "los_rate",
  "predicted_miss_distance",
  "estimation_position_error",
  "covariance_trace",
  "nis",
  "nees",
  "lateral_acceleration",
  "dynamics_model",
  "rudder_angle",
  "elevator_angle",
  "propulsion_force",
  "control_effort",
  "actuator_tracking_error",
  "orientation_w",
  "orientation_x",
  "orientation_y",
  "orientation_z",
  "command_saturated",
  "seeker_status",
] as const;

export function telemetryToCsv(samples: readonly TelemetrySample[]): string {
  const rows = samples.map((sample) => [
    sample.timestamp,
    sample.torpedo.position.x,
    sample.torpedo.position.z,
    sample.target.position.x,
    sample.target.position.z,
    sample.estimate?.position.x ?? "",
    sample.estimate?.position.z ?? "",
    sample.metrics.range,
    sample.metrics.horizontalRange,
    sample.metrics.verticalSeparation,
    sample.metrics.closingVelocity,
    sample.metrics.losRate,
    sample.metrics.predictedMissDistance,
    sample.estimationPositionError ?? "",
    sample.covarianceTrace ?? "",
    sample.estimate?.nis ?? "",
    sample.nees ?? "",
    sample.guidance.lateralAcceleration,
    sample.torpedo.dynamicsModel,
    sample.torpedo.actuator.rudderAngle,
    sample.torpedo.actuator.elevatorAngle,
    sample.torpedo.actuator.propulsionForce,
    sample.torpedo.actuator.controlEffort,
    sample.torpedo.actuator.trackingError,
    sample.torpedo.orientation.w,
    sample.torpedo.orientation.x,
    sample.torpedo.orientation.y,
    sample.torpedo.orientation.z,
    sample.guidance.saturated || sample.torpedo.actuator.saturated,
    sample.seekerStatus,
  ]);
  return [columns.join(","), ...rows.map((row) => row.join(","))].join(
    "\n",
  );
}
